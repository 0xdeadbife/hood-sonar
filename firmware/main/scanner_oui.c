unsigned int scanner_oui_count(void) {
    return (unsigned int)(sizeof(OUI_TABLE) / sizeof(OUI_TABLE[0]));
}

bool scanner_oui_lookup(const uint8_t *mac, const char **vendor, cat_t *cat) {
    for (unsigned int i = 0; i < scanner_oui_count(); i++) {
        if (OUI_TABLE[i].oui[0] == mac[0] &&
            OUI_TABLE[i].oui[1] == mac[1] &&
            OUI_TABLE[i].oui[2] == mac[2]) {
            if (vendor) *vendor = OUI_TABLE[i].vendor;
            if (cat)    *cat    = OUI_TABLE[i].cat;
            return true;
        }
    }
    if (vendor) *vendor = "";
    if (cat)    *cat    = CAT_UNKNOWN;
    return false;
}
